import {
  postOrUpdatePRComment,
} from "@github-ai-actions/github";
import {
  formatFindings,
  formatScoreCard,
  formatReviewHeader,
  type Finding,
  type ScoreCard,
  Logger,
} from "@github-ai-actions/utils";
import type { Octokit } from "@octokit/rest";

import type { ReviewAnalysis } from "./types.js";

const logger = new Logger("pr-review:output");

const ACTION_VERSION = "1.0.0";

/**
 * Format and post the review to GitHub.
 */
export class ReviewOutputter {
  constructor(
    private readonly octokit: Octokit,
    private readonly owner: string,
    private readonly repo: string,
    private readonly prNumber: number,
    private readonly dryRun: boolean,
  ) {}

  /**
   * Build the full review comment Markdown and optionally post it.
   */
  async postReview(analysis: ReviewAnalysis): Promise<{
    commentBody: string;
    commentUrl?: string;
    commentId?: number;
  }> {
    const commentBody = this.buildReviewComment(analysis);

    if (this.dryRun) {
      logger.info("[Dry Run] Would post the following review:");
      logger.info(commentBody.slice(0, 500) + "...");
      return { commentBody };
    }

    const { commentId, isNew } = await postOrUpdatePRComment(
      this.octokit,
      this.owner,
      this.repo,
      this.prNumber,
      commentBody,
    );

    const action = isNew ? "Posted new" : "Updated existing";
    logger.info(`${action} review comment #${commentId}`);

    return {
      commentBody,
      commentId,
      commentUrl: `https://github.com/${this.owner}/${this.repo}/pull/${this.prNumber}#issuecomment-${commentId}`,
    };
  }

  /** Build the complete review Markdown */
  private buildReviewComment(analysis: ReviewAnalysis): string {
    const findings: Finding[] = analysis.findings.map((f) => ({
      severity: f.severity,
      category: f.category,
      title: f.title,
      description: f.description,
      file: f.file,
      line: f.line,
      suggestion: f.suggestion,
      codeExample: f.codeExample,
    }));

    const scoreCard: ScoreCard = {
      overall: analysis.scoreCard.overall,
      breakdown: analysis.scoreCard.breakdown,
      summary: analysis.scoreCard.summary,
    };

    const sections: string[] = [
      formatReviewHeader(ACTION_VERSION),
      formatScoreCard(scoreCard),
      "",
      formatFindings(findings),
      "",
      this.buildSummarySection(analysis),
      "",
      this.buildFooter(),
    ];

    return sections.join("\n");
  }

  private buildSummarySection(analysis: ReviewAnalysis): string {
    const actionEmoji: Record<string, string> = {
      approve: "✅",
      comment: "💬",
      request_changes: "🔴",
    };

    const emoji = actionEmoji[analysis.suggestedAction] ?? "💬";

    return [
      "## 📝 Summary",
      "",
      analysis.summary,
      "",
      `**Suggested Action:** ${emoji} ${analysis.suggestedAction.replace("_", " ").toUpperCase()}`,
    ].join("\n");
  }

  private buildFooter(): string {
    return [
      "<details>",
      `<summary>🤖 About this review</summary>`,
      "",
      `This review was generated by [GitHub AI Actions](https://github.com/github-ai-actions/github-ai-actions) v${ACTION_VERSION}.`,
      "AI-generated reviews may contain errors. Always use human judgment before merging.",
      "",
      "</details>",
    ].join("\n");
  }
}
