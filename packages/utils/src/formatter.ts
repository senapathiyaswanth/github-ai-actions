/**
 * Markdown formatting utilities for GitHub AI Actions output.
 * Produces GitHub-Flavored Markdown (GFM) compatible output.
 */

/** Severity levels for review findings */
export type Severity = "critical" | "high" | "medium" | "low" | "info";

/** A single review finding/issue */
export interface Finding {
  severity: Severity;
  category: string;
  title: string;
  description: string;
  file?: string;
  line?: number;
  suggestion?: string;
  codeExample?: string;
}

/** Overall quality score card */
export interface ScoreCard {
  overall: number; // 0–100
  breakdown: {
    correctness: number;
    security: number;
    maintainability: number;
    performance: number;
    style: number;
  };
  summary: string;
}

const SEVERITY_EMOJI: Record<Severity, string> = {
  critical: "🔴",
  high: "🟠",
  medium: "🟡",
  low: "🔵",
  info: "⚪",
};

const SEVERITY_LABEL: Record<Severity, string> = {
  critical: "CRITICAL",
  high: "HIGH",
  medium: "MEDIUM",
  low: "LOW",
  info: "INFO",
};

/** Format a quality score as a visual progress bar */
export function formatScoreBar(score: number): string {
  const clamped = Math.max(0, Math.min(100, Math.round(score)));
  const filled = Math.round(clamped / 10);
  const empty = 10 - filled;
  const bar = "█".repeat(filled) + "░".repeat(empty);

  let emoji = "✅";
  if (clamped < 40) emoji = "❌";
  else if (clamped < 70) emoji = "⚠️";

  return `${emoji} \`${bar}\` **${clamped}/100**`;
}

/** Format a severity badge */
export function formatSeverityBadge(severity: Severity): string {
  return `${SEVERITY_EMOJI[severity]} \`${SEVERITY_LABEL[severity]}\``;
}

/** Format a single finding as a markdown block */
export function formatFinding(finding: Finding, index: number): string {
  const lines: string[] = [
    `### ${index + 1}. ${formatSeverityBadge(finding.severity)} ${finding.title}`,
    "",
    `**Category:** ${finding.category}`,
    "",
    finding.description,
  ];

  if (finding.file) {
    const location = finding.line ? `${finding.file}:${finding.line}` : finding.file;
    lines.push("", `**Location:** \`${location}\``);
  }

  if (finding.suggestion) {
    lines.push("", "**💡 Suggestion:**", "", finding.suggestion);
  }

  if (finding.codeExample) {
    lines.push("", "**Example fix:**", "", "```typescript", finding.codeExample, "```");
  }

  return lines.join("\n");
}

/** Format a full score card */
export function formatScoreCard(scoreCard: ScoreCard): string {
  const { overall, breakdown, summary } = scoreCard;
  const rows = Object.entries(breakdown)
    .map(([key, val]) => {
      const label = key.charAt(0).toUpperCase() + key.slice(1);
      return `| ${label} | ${formatScoreBar(val)} |`;
    })
    .join("\n");

  return [
    "## 📊 Quality Score",
    "",
    `**Overall:** ${formatScoreBar(overall)}`,
    "",
    "| Dimension | Score |",
    "|-----------|-------|",
    rows,
    "",
    "### Summary",
    "",
    summary,
  ].join("\n");
}

/** Format an array of findings grouped by severity */
export function formatFindings(findings: Finding[]): string {
  if (findings.length === 0) {
    return "## ✅ No Issues Found\n\nThis looks great! No significant issues were detected.";
  }

  const bySeverity = groupBySeverity(findings);
  const sections: string[] = ["## 🔍 Findings"];

  const severityOrder: Severity[] = ["critical", "high", "medium", "low", "info"];
  let index = 0;

  for (const severity of severityOrder) {
    const group = bySeverity[severity];
    if (!group || group.length === 0) continue;

    sections.push(
      "",
      `### ${SEVERITY_EMOJI[severity]} ${SEVERITY_LABEL[severity]} (${group.length})`,
      "",
    );

    for (const finding of group) {
      sections.push(formatFinding(finding, index++), "");
    }
  }

  return sections.join("\n");
}

/** Group findings by severity level */
function groupBySeverity(findings: Finding[]): Partial<Record<Severity, Finding[]>> {
  return findings.reduce<Partial<Record<Severity, Finding[]>>>((acc, finding) => {
    const existing = acc[finding.severity] ?? [];
    return { ...acc, [finding.severity]: [...existing, finding] };
  }, {});
}

/** Format a PR review comment header */
export function formatReviewHeader(actionVersion: string): string {
  return [
    "<!-- github-ai-actions-review -->",
    "## 🤖 AI Code Review",
    "",
    `> Generated by [GitHub AI Actions](https://github.com/github-ai-actions/github-ai-actions) v${actionVersion}`,
    "",
  ].join("\n");
}

/** Format release notes from structured data */
export function formatReleaseNotes(
  version: string,
  date: string,
  sections: Record<string, string[]>,
  breaking: string[],
): string {
  const lines: string[] = [`# Release ${version} — ${date}`, ""];

  if (breaking.length > 0) {
    lines.push("## ⚠️ Breaking Changes", "");
    for (const change of breaking) lines.push(`- ${change}`);
    lines.push("");
  }

  const sectionOrder = ["Features", "Bug Fixes", "Performance", "Documentation", "Chores"];
  for (const section of sectionOrder) {
    const items = sections[section];
    if (items && items.length > 0) {
      lines.push(`## ${section}`, "");
      for (const item of items) lines.push(`- ${item}`);
      lines.push("");
    }
  }

  // Any remaining sections not in the predefined order
  for (const [section, items] of Object.entries(sections)) {
    if (!sectionOrder.includes(section) && items.length > 0) {
      lines.push(`## ${section}`, "");
      for (const item of items) lines.push(`- ${item}`);
      lines.push("");
    }
  }

  return lines.join("\n").trimEnd();
}

/** Escape markdown special characters */
export function escapeMarkdown(text: string): string {
  return text.replace(/[*_`[\]()~>#+=|{}.!-]/g, "\\$&");
}

/** Convert plain text to a markdown code block */
export function codeBlock(code: string, language = ""): string {
  return `\`\`\`${language}\n${code}\n\`\`\``;
}
